export const messages = { en, zh };
export const localePath = (locale: Locale, path = "/"): string => locale === "zh" ? `/zh${path}` : path;

export function languagePath(pathname: string, locale: Locale): string {
  const base = process.env.NEXT_PUBLIC_BASE_PATH ?? "";
  const path = base && (pathname === base || pathname.startsWith(`${base}/`)) ? pathname.slice(base.length) || "/" : pathname;
  const unlocalized = path === "/zh" ? "/" : path.startsWith("/zh/") ? path.slice(3) : path;
  return localePath(locale, unlocalized.endsWith("/") ? unlocalized : `${unlocalized}/`);
}

export const conceptCount = (locale: Locale, count: number): string => locale === "zh" ? `${count} 个概念` : `${count} ${count === 1 ? "concept" : "concepts"}`;
export const resultsText = (locale: Locale, count: number, query: string): string => locale === "zh"
  ? `${query ? `“${query}”的搜索结果：` : ""}${count} 个概念可探索`
  : `${conceptCount(locale, count)} to explore${query ? ` for “${query}”` : ""}`;
export const animationLabel = (locale: Locale, action: "play" | "pause" | "replay", title: string): string => locale === "zh"
  ? `${messages.zh[action]}${title}动画`
  : `${messages.en[action]} ${title} animation`;
export const copyLabel = (locale: Locale, title: string): string => locale === "zh" ? `复制${title}提示词` : `Copy ${title} prompt`;

